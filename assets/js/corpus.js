  /* ------------------------------------------------------------------ */
  /* 2. Дагаврын жагсаалт (урт → богино)                                */
  /* ------------------------------------------------------------------ */
  var SUFFIXES = [
    'нуудын', 'уудын', 'үүдийн', 'нүүдийн', 'нууд', 'ууд', 'үүд', 'нүүд',
    'ийнх', 'ынх', 'дээрээ', 'даараа', 'гүйгээр', 'аараа', 'ээрээ', 'оороо', 'өөрөө',
    'ийн', 'ний', 'ын', 'ны', 'аас', 'ээс', 'оос', 'өөс', 'тай', 'той', 'тэй',
    'луу', 'лүү', 'руу', 'рүү', 'аар', 'ээр', 'оор', 'өөр', 'ийг', 'ыг',
    'даа', 'дээ', 'доо', 'дөө', 'лаа', 'лээ', 'лоо', 'лөө', 'сан', 'сэн', 'сон', 'сөн',
    'чид', 'дад', 'дэд', 'над', 'над', 'ад', 'эд', 'од', 'өд', 'ид', 'ыг',
    'д', 'т', 'г', 'ж'
  ];

  var BOS = '<эхлэл>';
  var UNK = '<үл-мэдэгдэх>';
  var WORD_RE = /[a-zа-яёөү0-9]+|[.,!?;:]/gi;

  function splitWords(text) {
    var m = String(text).toLowerCase().match(WORD_RE);
    return m ? m : [];
  }

  /* ------------------------------------------------------------------ */
  /* 3. Толь бичиг байгуулах (BPE-тэй төстэй хоёр дамжлага)             */
  /* ------------------------------------------------------------------ */
  var wordCount = Object.create(null);
  CORPUS.forEach(function (line) {
    splitWords(line).forEach(function (w) {
      wordCount[w] = (wordCount[w] || 0) + 1;
    });
  });

  // Хангалттай олон давтагдсан үгсийг бүтэн байлгана.
  var frequent = Object.create(null);
  Object.keys(wordCount).forEach(function (w) {
    if (wordCount[w] >= 2) frequent[w] = true;
  });

  /**
   * Нэг үгийг дэд нэгжүүд рүү задална.
   * — Байнга тохиолддог үг бол бүтнээр нь.
   * — Эс бөгөөс "үндэс + дагавар" болгож задлахыг оролдоно
   *   (үндэс нь мэдэгдэж буй үг байх ёстой).
   * — Толь бичигт огт байхгүй бол <үл-мэдэгдэх>.
   */
  function splitWordToUnits(word, known) {
    if (known[word]) return [word];
    for (var i = 0; i < SUFFIXES.length; i++) {
      var suf = SUFFIXES[i];
      if (word.length > suf.length + 1 && word.slice(-suf.length) === suf) {
        var stem = word.slice(0, word.length - suf.length);
        if (known[stem]) return [stem, '##' + suf];
      }
    }
    return null; // шийдэгдээгүй
  }

  // 2-р дамжлага: корпусыг эцсийн токен урсгал болгож задлана.
  var vocabSet = Object.create(null);
  Object.keys(frequent).forEach(function (w) { vocabSet[w] = true; });

  var sentences = CORPUS.map(function (line) {
    var out = [BOS];
    splitWords(line).forEach(function (w) {
      var units = splitWordToUnits(w, frequent);
      if (units === null) units = [w]; // ховор боловч задрахгүй үг — бүтнээр нь
      units.forEach(function (u) { vocabSet[u] = true; out.push(u); });
    });
    return out;
  });

  vocabSet[UNK] = true;
  vocabSet[BOS] = true;

  var vocab = Object.keys(vocabSet).sort();
  var tokenToId = Object.create(null);
  vocab.forEach(function (t, i) { tokenToId[t] = i; });

  /* ------------------------------------------------------------------ */
  /* 4. Хэрэглэгчийн текстийг токенчлох                                  */
  /* ------------------------------------------------------------------ */
  /**
   * @param {string} text
   * @returns {{text:string, token:string, id:number, unknown:boolean}[]}
   */
  function tokenize(text) {
    var result = [{ text: BOS, token: BOS, id: tokenToId[BOS], unknown: false, special: true }];
    splitWords(text).forEach(function (w) {
      var units = splitWordToUnits(w, vocabSet);
      var isUnknown = false;
      if (units === null) {
        if (vocabSet[w]) {
          units = [w];
        } else {
          units = [UNK];
          isUnknown = true;
        }
      }
      units.forEach(function (u, idx) {
        result.push({
          text: isUnknown ? w : (idx === 0 ? u : u.replace('##', '')),
          token: u,
          id: tokenToId[u],
          unknown: isUnknown,
          continuation: idx > 0
        });
      });
    });
    return result;
  }

  function detokenize(tokens) {
    return tokens
      .filter(function (t) { return !t.special; })
      .map(function (t, i) {
        if (t.continuation || /^[.,!?;:]$/.test(t.text)) return t.text;
        return (i === 0 ? '' : ' ') + t.text;
      })
      .join('');
  }

  TE.corpus = {
    CORPUS: CORPUS,
    SUFFIXES: SUFFIXES,
    BOS: BOS,
    UNK: UNK,
    sentences: sentences,
    vocab: vocab,
    tokenToId: tokenToId,
    tokenize: tokenize,
    detokenize: detokenize,
    splitWords: splitWords
  };
